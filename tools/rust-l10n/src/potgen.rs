fn is_rule_id(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_lowercase() || c.is_ascii_digit() => {}
        _ => return false,
    }
    s.bytes()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

/// Разобрать skip-политику (JSON-текст) с понятными ошибками.
pub fn parse_skip_policy(text: &str, source: &str) -> Result<SkipPolicy, String> {
    let value: Value = serde_json::from_str(text)
        .map_err(|e| format!("невалидный JSON skip-политики {source}: {e}"))?;
    let Value::Object(map) = value else {
        return Err(format!(
            "skip-политика {source}: ожидался объект {{\"rules\": [...]}}"
        ));
    };
    for key in map.keys() {
        if key != "rules" && !key.starts_with('_') {
            return Err(format!(
                "skip-политика {source}: неизвестное поле \"{key}\" (допустимы rules и _комментарии)"
            ));
        }
    }
    let Some(Value::Array(items)) = map.get("rules") else {
        return Err(format!(
            "skip-политика {source}: поле \"rules\" должно быть массивом правил"
        ));
    };

    let mut rules: Vec<SkipRule> = Vec::with_capacity(items.len());
    let mut seen: HashSet<String> = HashSet::new();
    for (index, item) in items.iter().enumerate() {
        let n = index + 1;
        let Value::Object(rule) = item else {
            return Err(format!("skip-политика {source}: правило #{n} — не объект"));
        };
        for key in rule.keys() {
            if key != "id"
                && key != "src"
                && key != "srcExclude"
                && key != "when"
                && key != "enabled"
            {
                return Err(format!(
                    "skip-политика {source}: правило #{n} — неизвестное поле \"{key}\""
                ));
            }
        }
        let Some(Value::String(id)) = rule.get("id") else {
            return Err(format!(
                "skip-политика {source}: правило #{n} — id обязателен"
            ));
        };
        if !is_rule_id(id) {
            return Err(format!(
                "skip-политика {source}: правило #{n} — id \"{id}\" не по грамматике [a-z0-9-]"
            ));
        }
        if !seen.insert(id.clone()) {
            return Err(format!(
                "skip-политика {source}: id правила повторяется: \"{id}\""
            ));
        }
        let Some(Value::String(src)) = rule.get("src") else {
            return Err(format!(
                "skip-политика {source}: правило \"{id}\" — src обязателен"
            ));
        };
        validate_policy_pattern(src)
            .map_err(|e| format!("skip-политика {source}: правило \"{id}\" — {e}"))?;
        let mut src_exclude: Vec<String> = Vec::new();
        match rule.get("srcExclude") {
            None => {}
            Some(Value::Array(items)) => {
                for pattern in items {
                    let Value::String(pattern) = pattern else {
                        return Err(format!(
                            "skip-политика {source}: правило \"{id}\" — srcExclude: ожидалась строка"
                        ));
                    };
                    validate_policy_pattern(pattern).map_err(|e| {
                        format!("skip-политика {source}: правило \"{id}\" — srcExclude: {e}")
                    })?;
                    src_exclude.push(pattern.clone());
                }
            }
            Some(other) => {
                return Err(format!(
                    "skip-политика {source}: правило \"{id}\" — srcExclude должен быть массивом меток: {other}"
                ));
            }
        }
        let Some(Value::String(when_raw)) = rule.get("when") else {
            return Err(format!(
                "skip-политика {source}: правило \"{id}\" — when обязателен"
            ));
        };
        let Some(when) = SkipCondition::parse(when_raw) else {
            return Err(format!(
                "skip-политика {source}: правило \"{id}\" — неизвестное условие \"{when_raw}\" \
                 (допустимо: noLetters, shortToken, noWord, identifier, fragment)"
            ));
        };
        let enabled = match rule.get("enabled") {
            None => true,
            Some(Value::Bool(value)) => *value,
            Some(other) => {
                let message = format!(
                    "skip-политика {source}: правило \"{id}\" — enabled должен быть boolean: {other}"
                );
                return Err(message);
            }
        };
        rules.push(SkipRule {
            id: id.clone(),
            src: src.clone(),
            src_exclude,
            when,
            enabled,
        });
    }

    Ok(SkipPolicy {
        path: source.to_string(),
        rules,
    })
}

/// Прочитать skip-политику с диска; `required` — отсутствие файла это ошибка.
pub fn load_skip_policy(path: &Path, required: bool) -> Result<Option<SkipPolicy>, String> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(Some(parse_skip_policy(&text, &path.display().to_string())?)),
        Err(err) if !required && err.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(err) => Err(format!(
            "skip-политика не читается {}: {err}",
            path.display()
        )),
    }
}

/// Найти `config/pot-skip-policy.json` в `start` или выше.
pub fn discover_skip_policy_path(start: &Path) -> Option<PathBuf> {
    let mut dir = std::fs::canonicalize(start).unwrap_or_else(|_| {
        std::env::current_dir()
            .map(|cwd| cwd.join(start))
            .unwrap_or_else(|_| start.to_path_buf())
    });
    loop {
        let candidate = dir.join("config").join("pot-skip-policy.json");
        if candidate.is_file() {
            let text = candidate.to_string_lossy();
            return Some(match text.strip_prefix(r"\\?\") {
                Some(rest) => PathBuf::from(rest),
                None => candidate,
            });
        }
        if !dir.pop() {
            return None;
        }
    }
}

/// Применить skip-политику к каталогу: пометить записи, собрать журнал.
///
/// Побеждает ПЕРВОЕ подходящее правило в порядке политики (порядок — данные,
/// поэтому результат детерминирован). Записи не удаляются и не меняются.
pub fn apply_skip_policy(
    catalog: &mut Catalog,
    policy: &SkipPolicy,
) -> (usize, Vec<SkipJournalEntry>, Vec<(String, usize)>) {
    let mut keys: Vec<(String, String)> = Vec::with_capacity(catalog_size(catalog));
    for (text, by_ctxt) in catalog.iter() {
        for ctxt in by_ctxt.keys() {
            keys.push((text.clone(), ctxt.clone()));
        }
    }
    keys.sort_by(|a, b| a.0.cmp(&b.0).then_with(|| a.1.cmp(&b.1)));

    let active: Vec<&SkipRule> = policy.rules.iter().filter(|r| r.enabled).collect();
    let mut counts: Vec<usize> = vec![0; active.len()];
    let mut journal: Vec<SkipJournalEntry> = Vec::new();

    for (text, ctxt) in keys {
        let slot = catalog
            .get_mut(&text)
            .and_then(|by_ctxt| by_ctxt.get_mut(&ctxt))
            .expect("ключ из каталога");
        let rich = slot
            .comments
            .iter()
            .find_map(|c| c.strip_prefix("rich_text: "))
            .unwrap_or("");
        let Some(index) = active.iter().position(|rule| {
            src_matches_pattern(&rule.src, &slot.src)
                && !rule
                    .src_exclude
                    .iter()
                    .any(|pattern| src_matches_pattern(pattern, &slot.src))
                && skip_condition_matches(rule.when, &text, rich)
        }) else {
            continue;
        };
        let rule = active[index];
        slot.skip = Some(rule.id.clone());
        counts[index] += 1;
        journal.push(SkipJournalEntry {
            rule: rule.id.clone(),
            src: slot.src.clone(),
            msgid: text,
            msgctxt: ctxt,
        });
    }

    let by_rule: Vec<(String, usize)> = active
        .iter()
        .zip(counts.iter())
        .map(|(rule, count)| (rule.id.clone(), *count))
        .collect();
    (journal.len(), journal, by_rule)
}

/// id правила для записей из `config/pot-skip-ids.json`.
pub const REVIEWED_RULE_ID: &str = "reviewed";

/// Разобрать `{"skip": ["msgid", …]}` (подтверждённые человеком решения).
pub fn parse_skip_ids(text: &str, source: &str) -> Result<HashSet<String>, String> {
    let value: Value = serde_json::from_str(text)
        .map_err(|e| format!("невалидный JSON списка skip-id {source}: {e}"))?;
    let Value::Object(map) = value else {
        return Err(format!(
            "список skip-id {source}: ожидался объект {{\"skip\": [...]}}"
        ));
    };
    for key in map.keys() {
        if key != "skip" && !key.starts_with('_') {
            return Err(format!(
                "список skip-id {source}: неизвестное поле \"{key}\""
            ));
        }
    }
    let Some(Value::Array(items)) = map.get("skip") else {
        return Err(format!(
            "список skip-id {source}: поле \"skip\" должно быть массивом строк"
        ));
    };
    let mut out = HashSet::new();
    for item in items {
        let Value::String(text) = item else {
            return Err(format!(
                "список skip-id {source}: ожидалась строка, получено {item}"
            ));
        };
        if text.is_empty() {
            return Err(format!("список skip-id {source}: пустая строка"));
        }
        out.insert(text.clone());
    }
    Ok(out)
}

/// Прочитать список с диска (нет файла — пусто).
pub fn load_skip_ids(path: &Path) -> Result<Option<HashSet<String>>, String> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(Some(parse_skip_ids(&text, &path.display().to_string())?)),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(err) => Err(format!(
            "список skip-id не читается {}: {err}",
            path.display()
        )),
    }
}

/// Найти `config/pot-skip-ids.json` в `start` или выше (как у политик).
pub fn discover_skip_ids_path(start: &Path) -> Option<PathBuf> {
    let mut dir = if start.as_os_str().is_empty() {
        PathBuf::from(".")
    } else {
        start.to_path_buf()
    };
    loop {
        let candidate = dir.join("config").join("pot-skip-ids.json");
        if candidate.exists() {
            return Some(candidate);
        }
        match dir.parent() {
            Some(parent) if parent != dir => dir = parent.to_path_buf(),
            _ => return None,
        }
    }
}

/// Пометить записи из подтверждённого списка. Уже помеченные правилом
/// сохраняют свою причину; возвращаем (новых, журнал, неиспользованных).
pub fn apply_skip_ids(
    catalog: &mut Catalog,
    ids: &HashSet<String>,
) -> (usize, Vec<SkipJournalEntry>, usize) {
    let mut marked = 0usize;
    let mut used: HashSet<String> = HashSet::new();
    let mut journal: Vec<SkipJournalEntry> = Vec::new();
    for (text, by_ctxt) in catalog.iter_mut() {
        if !ids.contains(text) {
            continue;
        }
        used.insert(text.clone());
        for (ctxt, slot) in by_ctxt.iter_mut() {
            if slot.skip.is_some() {
                continue;
            }
            slot.skip = Some(REVIEWED_RULE_ID.to_string());
            marked += 1;
            journal.push(SkipJournalEntry {
                rule: REVIEWED_RULE_ID.to_string(),
                src: slot.src.clone(),
                msgid: text.clone(),
                msgctxt: ctxt.clone(),
            });
        }
    }
    (marked, journal, ids.len().saturating_sub(used.len()))
}

/// Журнал skip как JSONL (по строке на запись, порядок POT).
pub fn render_skip_journal_jsonl(entries: &[SkipJournalEntry]) -> Result<String, String> {
    let mut out = String::new();
    for entry in entries {
        let line = serde_json::to_string(entry).map_err(|e| format!("журнал skip: {e}"))?;
        out.push_str(&line);
        out.push('\n');
    }
    Ok(out)
}

/// Запись журнала skip: `.part` с PID → rename (как у журнала исключённых).
pub fn write_skip_journal(path: &Path, entries: &[SkipJournalEntry]) -> Result<(), String> {
    write_journal(path, &render_skip_journal_jsonl(entries)?)
}

/// Слот каталога: провенанс и комментарии будущей записи.
#[derive(Debug, Default)]
pub struct Slot {
    /// `dialog`/`bundle`/`field:*`/`settings`/`us`/`raw:*`/`global`.
    pub src: String,
    pub comments: Vec<String>,
    /// Id правила skip-политики: в POT даёт `#, skip` и `#. skip: <id>`.
    pub skip: Option<String>,
}

/// msgid → msgctxt → слот. Порядок не важен: рендер сортирует ключи.
pub type Catalog = HashMap<String, HashMap<String, Slot>>;

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct PotStats {
    pub scanned: usize,
    pub new: usize,
    pub vanished: usize,
    pub triaged: usize,
    pub rich: usize,
    pub merged_twins: usize,
}

/// Собрать каталог из инвентаря (аналог `build_pot_update`).
///
/// `old_keys` — пары (msgid, msgctxt) из прежнего POT: нужны только для
/// статистики new/vanished, на содержимое не влияют.
/// Предикат «метка исключена политикой» (для дедупа).
pub type ExcludeFn<'a> = Box<dyn Fn(&str) -> bool + 'a>;

pub fn build_catalog(
    items: &[InventoryItem],
    old_keys: &HashSet<(String, String)>,
    // `is_excluded` — признак «метка исключена политикой». Нужен при дедупе:
    // если строку доставили и ассет (`raw:GameObject`), и живой источник
    // (`dialog`), победить обязан живой — иначе срез ассетов унесёт текст.
    is_excluded: Option<&dyn Fn(&str) -> bool>,
) -> (Catalog, PotStats) {
    let mut catalog: Catalog = HashMap::new();
    let mut seen: HashSet<(String, String)> = HashSet::new();
    let mut stats = PotStats::default();

    for item in items {
        stats.scanned += 1;
        let ctxt = ctxt_of(item);

        let mut rich = py_strip(&strip_font_tags(&item.rich_text)).to_string();
        if rich == item.text {
            // Форматирования нет, просто копия текста.
            rich.clear();
        }
        let key = (item.text.clone(), ctxt.clone());
        if seen.contains(&key) {
            // Двойник: один перевод на все вхождения. rich обновляем, только
            // если у первого вхождения его не было.
            //
            // Если слот занял исключённый источник, а сейчас пришёл живой —
            // переключаем метку на живой: иначе строка выпадет вместе с ассетом.
            if let Some(is_excluded) = is_excluded {
                if let Some(slot) = catalog
                    .get_mut(&item.text)
                    .and_then(|by_ctxt| by_ctxt.get_mut(&ctxt))
                {
                    if !slot.src.is_empty() && is_excluded(&slot.src) && !is_excluded(&item.src) {
                        slot.src = item.src.clone();
                    }
                }
            }
            if !rich.is_empty() {
                if let Some(slot) = catalog
                    .get_mut(&item.text)
                    .and_then(|by_ctxt| by_ctxt.get_mut(&ctxt))
                {
                    if !slot.comments.iter().any(|c| c.starts_with("rich_text:")) {
                        slot.comments.push(format!("rich_text: {rich}"));
                        stats.rich += 1;
                    }
                }
            }
            continue;
        }
        seen.insert(key.clone());

        let slot = catalog
            .entry(item.text.clone())
            .or_default()
            .entry(ctxt)
            .or_default();
        // src — первого вхождения: при дедупе это и есть путь доставки строки
        // в POT (как правило «первое вхождение побеждает» у rich_text).
        if slot.src.is_empty() {
            slot.src = item.src.clone();
        }
        if !rich.is_empty() {
            let comment = format!("rich_text: {rich}");
            if !slot.comments.contains(&comment) {
                slot.comments.push(comment);
                stats.rich += 1;
            }
        }
        if !old_keys.contains(&key) {
            stats.new += 1;
        }
        if !triage_reason(&item.text, item.kind).is_empty() {
            stats.triaged += 1;
        }
    }

    // Cross-source dedup: ui-двойник диалоговой/спикерской строки удаляем —
    // рантайм ищет по голому тексту, иначе один текст переводится дважды.
    let mut non_ui_texts: HashSet<String> = HashSet::new();
    for (text, by_ctxt) in &catalog {
        if by_ctxt.keys().any(|c| c != "ui") {
            non_ui_texts.insert(text.clone());
        }
    }
    let mut removed: Vec<String> = Vec::new();
    for (text, by_ctxt) in catalog.iter_mut() {
        if by_ctxt.contains_key("ui") && non_ui_texts.contains(text.as_str()) {
            by_ctxt.remove("ui");
            stats.merged_twins += 1;
            if by_ctxt.is_empty() {
                removed.push(text.clone());
            }
        }
    }
    for text in removed {
        catalog.remove(&text);
    }

    for key in old_keys {
        if !seen.contains(key) {
            stats.vanished += 1;
        }
    }

    (catalog, stats)
}

/// Число записей каталога (msgid × msgctxt).
pub fn catalog_size(catalog: &Catalog) -> usize {
    catalog.values().map(HashMap::len).sum()
}

/// Отрендерить каталог в POT (сортировка по msgid, затем msgctxt).
pub fn render_pot(catalog: &Catalog, created: &str) -> String {
    let mut keys: Vec<(&str, &str)> = Vec::with_capacity(catalog_size(catalog));
    for (text, by_ctxt) in catalog {
        for ctxt in by_ctxt.keys() {
            keys.push((text.as_str(), ctxt.as_str()));
        }
    }
    // Rust `str` Ord — побайтовый, для UTF-8 он же порядок code points.
    keys.sort_by(|a, b| a.0.cmp(b.0).then_with(|| a.1.cmp(b.1)));

    let entries: Vec<PoEntry> = keys
        .into_iter()
        .map(|(text, ctxt)| {
            let slot = &catalog[text][ctxt];
            let mut comments = Vec::with_capacity(slot.comments.len() + 2);
            if !slot.src.is_empty() {
                // Провенанс — первым комментарием (рядом с rich_text).
                comments.push(format!("src: {}", slot.src));
            }
            // Причина «не переводить» — до текста, чтобы её видел человек.
            if let Some(rule) = &slot.skip {
                comments.push(format!("skip: {rule}"));
            }
            comments.extend(slot.comments.iter().cloned());
            let mut entry = PoEntry {
                msgid: text.to_string(),
                msgctxt: ctxt.to_string(),
                comments,
                ..PoEntry::default()
            };
            if slot.skip.is_some() {
                entry.flags.push("skip".to_string());
            }
            entry
        })
        .collect();

    render_po(&entries, &pot_header_lines(created))
}

/// Ключи (msgid, msgctxt) существующего POT — для статистики.
pub fn old_keys_from_pot(path: &Path) -> HashSet<(String, String)> {
    let mut keys = HashSet::new();
    let Ok(text) = std::fs::read_to_string(path) else {
        return keys;
    };
    for e in parse_po(&text) {
        if !e.msgid.is_empty() {
            keys.insert((e.msgid, e.msgctxt));
        }
    }
    keys
}

/// Атомарная запись: `.part` → rename (обрыв не обнуляет файл).
pub fn write_atomic(path: &Path, text: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    let part = PathBuf::from(format!("{}.part", path.display()));
    let write = std::fs::write(&part, text).map_err(|e| format!("{}: {e}", part.display()));
    if let Err(err) = write {
        let _ = std::fs::remove_file(&part);
        return Err(err);
    }
    std::fs::rename(&part, path).map_err(|e| {
        let _ = std::fs::remove_file(&part);
        format!("{}: {e}", path.display())
    })
}

