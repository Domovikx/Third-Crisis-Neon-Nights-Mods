/// Полный прогон: дамп → инвентарь → каталог → политика → POT.
///
/// Без `out_path` и без `update` пишет в `tmp/potgen/template.pot`;
/// `update: true` — в `po/template.pot`.
pub fn run(options: &PotgenOptions) -> Result<PotgenResult, String> {
    let dump_dir = if options.dump_dir.as_os_str().is_empty() {
        options.root.join("tmp").join("dump")
    } else {
        options.dump_dir.clone()
    };
    let inventory = scan_dump(&dump_dir)?;
    if inventory.items.is_empty() {
        return Err(format!(
            "empty dump: {} — переводимых строк не найдено",
            dump_dir.display()
        ));
    }

    // Ключи берём из репозиторного `po/template.pot` ВСЕГДА, даже если пишем
    // в другой файл: это только статистика new/vanished.
    let old_keys = old_keys_from_pot(&options.root.join("po").join("template.pot"));

    // Политика отбора по провенансу — данные (`config/pot-src-policy.json`).
    // Читается ДО сборки каталога: дедуп должен знать исключённые метки.
    let policy = match &options.policy {
        PolicySource::Disabled => None,
        PolicySource::Path(path) => load_src_policy(path, true)?,
        PolicySource::Default => {
            let start = if options.root.as_os_str().is_empty() {
                PathBuf::from(".")
            } else {
                options.root.clone()
            };
            match discover_policy_path(&start) {
                Some(path) => load_src_policy(&path, true)?,
                None => None,
            }
        }
    };

    let is_excluded: Option<ExcludeFn<'_>> = policy
        .as_ref()
        .map(|p| Box::new(move |src: &str| policy_decision(p, src).is_some()) as ExcludeFn<'_>);
    let is_excluded_ref: Option<&dyn Fn(&str) -> bool> = is_excluded.as_deref();
    let (catalog, stats) = build_catalog(&inventory.items, &old_keys, is_excluded_ref);
    if catalog_size(&catalog) == 0 {
        return Err("empty catalog: нечего записывать (пустой дамп?)".to_string());
    }

    let (catalog, excluded, by_src) = match &policy {
        Some(policy) => {
            let (kept, excluded, by_src) = apply_src_policy(catalog, policy);
            (kept, excluded, by_src)
        }
        None => (catalog, Vec::new(), Vec::new()),
    };
    let mut catalog = catalog;
    let entries = catalog_size(&catalog);
    if entries == 0 {
        return Err(format!(
            "empty catalog after policy: политика исключила все записи ({})",
            policy.as_ref().map(|p| p.path.clone()).unwrap_or_default()
        ));
    }

    // Skip-политика («перевод не нужен») — тоже данные; применяется ПОСЛЕ
    // отбора: помечаются только записи, реально попавшие в POT.
    let skip_policy = match &options.skip_policy {
        PolicySource::Disabled => None,
        PolicySource::Path(path) => load_skip_policy(path, true)?,
        PolicySource::Default => {
            let start = if options.root.as_os_str().is_empty() {
                PathBuf::from(".")
            } else {
                options.root.clone()
            };
            match discover_skip_policy_path(&start) {
                Some(path) => load_skip_policy(&path, true)?,
                None => None,
            }
        }
    };
    let skip_applied = match &skip_policy {
        Some(policy) => {
            let (marked, journal, by_rule) = apply_skip_policy(&mut catalog, policy);
            Some((marked, journal, by_rule))
        }
        None => None,
    };

    // Подтверждённые точечные skip-решения применяются ПОСЛЕ правил:
    // структурная причина точнее, чем «так решил классификатор».
    let skip_ids = match &options.skip_ids {
        PolicySource::Disabled => None,
        PolicySource::Path(path) => load_skip_ids(path)?,
        PolicySource::Default => match discover_skip_ids_path(&options.root) {
            Some(path) => load_skip_ids(&path)?,
            None => None,
        },
    };
    let ids_applied = skip_ids
        .as_ref()
        .map(|ids| apply_skip_ids(&mut catalog, ids));
    if let Some((_, _, unused)) = &ids_applied {
        if *unused > 0 {
            eprintln!(
                "skip-ids: {unused} записей из config/pot-skip-ids.json не найдены в POT (устаревшие? удали их из файла)"
            );
        }
    }

    let out_path = options.out_path.clone().unwrap_or_else(|| {
        if options.update {
            options.root.join("po").join("template.pot")
        } else {
            options.root.join("tmp").join("potgen").join("template.pot")
        }
    });
    let created = options
        .created
        .clone()
        .unwrap_or_else(|| format_pot_date(SystemTime::now()));
    let text = render_pot(&catalog, &created);
    write_atomic(&out_path, &text)?;

    let mut report: Option<PolicyReport> = None;
    let mut excluded_path: Option<PathBuf> = None;
    if let Some(policy) = &policy {
        // Журнал живёт в корне репозитория политики (`<...>/config/..`/tmp).
        let repo_root = Path::new(&policy.path)
            .parent()
            .and_then(|p| p.parent())
            .map(Path::to_path_buf)
            .unwrap_or_else(|| options.root.clone());
        let path = options
            .excluded_path
            .clone()
            .unwrap_or_else(|| repo_root.join("tmp").join("pot-excluded.jsonl"));
        write_excluded(&path, &excluded)?;
        excluded_path = Some(path);
        report = Some(PolicyReport {
            path: policy.path.clone(),
            excluded: excluded.len(),
            kept: entries,
            by_src,
        });
    }

    let mut skip_report: Option<SkipReport> = None;
    let mut skip_journal_path: Option<PathBuf> = None;
    if skip_applied.is_some() || ids_applied.is_some() {
        let mut journal: Vec<SkipJournalEntry> = Vec::new();
        let mut by_rule: Vec<(String, usize)> = Vec::new();
        let mut marked = 0usize;
        let mut paths: Vec<String> = Vec::new();
        if let (Some(policy), Some((m, j, r))) = (&skip_policy, &skip_applied) {
            marked += m;
            journal.extend(j.iter().cloned());
            by_rule.extend(r.iter().cloned());
            paths.push(policy.path.clone());
        }
        if let Some((m, j, _)) = &ids_applied {
            marked += m;
            journal.extend(j.iter().cloned());
            by_rule.push((REVIEWED_RULE_ID.to_string(), *m));
            let start = if options.root.as_os_str().is_empty() {
                PathBuf::from(".")
            } else {
                options.root.clone()
            };
            paths.push(
                start
                    .join("config")
                    .join("pot-skip-ids.json")
                    .display()
                    .to_string(),
            );
        }
        journal.sort_by(|a, b| {
            a.msgid
                .cmp(&b.msgid)
                .then_with(|| a.msgctxt.cmp(&b.msgctxt))
        });
        let repo_root = skip_policy
            .as_ref()
            .map(|p| {
                Path::new(&p.path)
                    .parent()
                    .and_then(|x| x.parent())
                    .map(Path::to_path_buf)
                    .unwrap_or_else(|| options.root.clone())
            })
            .unwrap_or_else(|| options.root.clone());
        let path = options
            .skip_journal_path
            .clone()
            .unwrap_or_else(|| repo_root.join("tmp").join("pot-skip.jsonl"));
        write_skip_journal(&path, &journal)?;
        skip_journal_path = Some(path);
        skip_report = Some(SkipReport {
            path: paths.join(" + "),
            marked,
            by_rule,
        });
    }

    Ok(PotgenResult {
        out_path,
        entries,
        bytes: text.len(),
        stats,
        policy: report,
        excluded_path,
        skip: skip_report,
        skip_journal_path,
    })
}
