//! potgen.rs — сборка `po/template.pot` из JSONL-дампа (1:1 с TS-эталоном
//! `.opencode/skills/extract-text/scripts/potgen.mts`).
//!
//! Контракт POT (менять только вместе с TS-эталоном):
//! - одна запись на уникальную пару (msgid, msgctxt);
//! - msgctxt: `speaker:<Имя>` / `speaker-name` / `ui`;
//! - `#:` refs не пишутся вовсе;
//! - `#. src: <метка>` — провенанс записи (путь доставки в POT);
//! - `#. rich_text: <разметка>` — исходная TMP-строка, `<font>`/`<material>`
//!   вырезаются (шрифт выбирает рантайм);
//! - ui-двойник строки с диалоговым/спикерским контекстом удаляется;
//! - записи отсортированы по (msgid, msgctxt).

use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use rust_l10n_core::po::{parse_po, render_po, PoEntry};

use crate::inventory::{py_strip, scan_dump, InventoryItem, ItemKind};
use crate::text_filters::{is_asset_name, is_garbage_fragment};

/// `</?(?:font|material)[^>]*>` с флагом `i`: вырезать теги шрифта/материала.
pub fn strip_font_tags(s: &str) -> String {
    if !s.contains('<') {
        return s.to_string();
    }
    let mut out = String::with_capacity(s.len());
    let bytes = s.as_bytes();
    let mut i = 0usize;
    while i < bytes.len() {
        if bytes[i] == b'<' {
            let mut j = i + 1;
            if j < bytes.len() && bytes[j] == b'/' {
                j += 1;
            }
            let rest = &bytes[j..];
            let kw = if rest.len() >= 4 && rest[..4].eq_ignore_ascii_case(b"font") {
                Some(4usize)
            } else if rest.len() >= 8 && rest[..8].eq_ignore_ascii_case(b"material") {
                Some(8usize)
            } else {
                None
            };
            if let Some(kw) = kw {
                let after = j + kw;
                if let Some(offset) = s[after..].find('>') {
                    i = after + offset + 1;
                    continue;
                }
            }
        }
        let ch = s[i..].chars().next().expect("граница символа");
        out.push(ch);
        i += ch.len_utf8();
    }
    out
}

/// Дата в формате Python `strftime("%Y-%m-%d %H:%M+0000")` (UTC).
pub fn format_pot_date(now: SystemTime) -> String {
    let secs = now
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let days = secs.div_euclid(86_400);
    let rem = secs.rem_euclid(86_400);
    let (year, month, day) = civil_from_days(days);
    format!(
        "{year:04}-{month:02}-{day:02} {:02}:{:02}+0000",
        rem / 3600,
        (rem % 3600) / 60
    )
}

/// Дни от 1970-01-01 → (год, месяц, день). Алгоритм Говарда Хиннанта
/// (`civil_from_days`), тот же, что в `chrono`: без внешних зависимостей.
fn civil_from_days(days: i64) -> (i64, i64, i64) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let mut year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = mp + if mp < 10 { 3 } else { -9 };
    if month <= 2 {
        year += 1;
    }
    (year, month, day)
}

/// Строки заголовка POT (пустую строку добавит `render_po`).
pub fn pot_header_lines(created: &str) -> Vec<String> {
    vec![
        // «potgen.py» оставлено намеренно: шапка входит в байт-паритет с POT.
        "# NeonTranslator EN template (generated by potgen.py — do not edit).".to_string(),
        "# Translate by copying to ru.po / de.po and filling msgstr.".to_string(),
        "msgid \"\"".to_string(),
        "msgstr \"\"".to_string(),
        "\"Project-Id-Version: NeonTranslator 1.0\\n\"".to_string(),
        format!("\"POT-Creation-Date: {created}\\n\""),
        "\"Content-Type: text/plain; charset=UTF-8\\n\"".to_string(),
        "\"Content-Transfer-Encoding: 8bit\\n\"".to_string(),
    ]
}

/// msgctxt записи: имя персонажа / речь персонажа / обычный UI-текст.
pub fn ctxt_of(item: &InventoryItem) -> String {
    match item.kind {
        ItemKind::Spk => "speaker-name".to_string(),
        _ if !item.speaker.is_empty() => format!("speaker:{}", item.speaker),
        _ => "ui".to_string(),
    }
}

/// Почему свежая строка не нуждается в переводе ("" = переводимая).
///
/// Авто-триаж применяется только к raw/settings (UI-ish), никогда к диалогам —
/// в истории может встретиться что угодно. В POT флаг не пишется: статистика.
pub fn triage_reason(text: &str, kind: ItemKind) -> &'static str {
    if !kind.is_ui_like() {
        return "";
    }
    if is_asset_name(text) {
        return "asset-name";
    }
    if is_garbage_fragment(text) {
        return "binary-garbage";
    }
    ""
}

/// Слот каталога: провенанс и комментарии будущей записи.
#[derive(Debug, Default)]
pub struct Slot {
    /// `dialog`/`bundle`/`field:*`/`settings`/`us`/`raw:*`/`global`.
    pub src: String,
    pub comments: Vec<String>,
}

/// msgid → msgctxt → слот. Порядок не важен: рендер сортирует ключи.
pub type Catalog = HashMap<String, HashMap<String, Slot>>;

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct PotStats {
    pub scanned: usize,
    pub new: usize,
    pub vanished: usize,
    pub triaged: usize,
    pub rich: usize,
    pub merged_twins: usize,
}

/// Собрать каталог из инвентаря (аналог `build_pot_update`).
///
/// `old_keys` — пары (msgid, msgctxt) из прежнего POT: нужны только для
/// статистики new/vanished, на содержимое не влияют.
pub fn build_catalog(
    items: &[InventoryItem],
    old_keys: &HashSet<(String, String)>,
) -> (Catalog, PotStats) {
    let mut catalog: Catalog = HashMap::new();
    let mut seen: HashSet<(String, String)> = HashSet::new();
    let mut stats = PotStats::default();

    for item in items {
        stats.scanned += 1;
        let ctxt = ctxt_of(item);

        let mut rich = py_strip(&strip_font_tags(&item.rich_text)).to_string();
        if rich == item.text {
            // Форматирования нет, просто копия текста.
            rich.clear();
        }
        let key = (item.text.clone(), ctxt.clone());
        if seen.contains(&key) {
            // Двойник: один перевод на все вхождения. rich обновляем, только
            // если у первого вхождения его не было.
            if !rich.is_empty() {
                if let Some(slot) = catalog
                    .get_mut(&item.text)
                    .and_then(|by_ctxt| by_ctxt.get_mut(&ctxt))
                {
                    if !slot.comments.iter().any(|c| c.starts_with("rich_text:")) {
                        slot.comments.push(format!("rich_text: {rich}"));
                        stats.rich += 1;
                    }
                }
            }
            continue;
        }
        seen.insert(key.clone());

        let slot = catalog
            .entry(item.text.clone())
            .or_default()
            .entry(ctxt)
            .or_default();
        // src — первого вхождения: при дедупе это и есть путь доставки строки
        // в POT (как правило «первое вхождение побеждает» у rich_text).
        if slot.src.is_empty() {
            slot.src = item.src.clone();
        }
        if !rich.is_empty() {
            let comment = format!("rich_text: {rich}");
            if !slot.comments.contains(&comment) {
                slot.comments.push(comment);
                stats.rich += 1;
            }
        }
        if !old_keys.contains(&key) {
            stats.new += 1;
        }
        if !triage_reason(&item.text, item.kind).is_empty() {
            stats.triaged += 1;
        }
    }

    // Cross-source dedup: ui-двойник диалоговой/спикерской строки удаляем —
    // рантайм ищет по голому тексту, иначе один текст переводится дважды.
    let mut non_ui_texts: HashSet<String> = HashSet::new();
    for (text, by_ctxt) in &catalog {
        if by_ctxt.keys().any(|c| c != "ui") {
            non_ui_texts.insert(text.clone());
        }
    }
    let mut removed: Vec<String> = Vec::new();
    for (text, by_ctxt) in catalog.iter_mut() {
        if by_ctxt.contains_key("ui") && non_ui_texts.contains(text.as_str()) {
            by_ctxt.remove("ui");
            stats.merged_twins += 1;
            if by_ctxt.is_empty() {
                removed.push(text.clone());
            }
        }
    }
    for text in removed {
        catalog.remove(&text);
    }

    for key in old_keys {
        if !seen.contains(key) {
            stats.vanished += 1;
        }
    }

    (catalog, stats)
}

/// Число записей каталога (msgid × msgctxt).
pub fn catalog_size(catalog: &Catalog) -> usize {
    catalog.values().map(HashMap::len).sum()
}

/// Отрендерить каталог в POT (сортировка по msgid, затем msgctxt).
pub fn render_pot(catalog: &Catalog, created: &str) -> String {
    let mut keys: Vec<(&str, &str)> = Vec::with_capacity(catalog_size(catalog));
    for (text, by_ctxt) in catalog {
        for ctxt in by_ctxt.keys() {
            keys.push((text.as_str(), ctxt.as_str()));
        }
    }
    // Rust `str` Ord — побайтовый, для UTF-8 он же порядок code points.
    keys.sort_by(|a, b| a.0.cmp(b.0).then_with(|| a.1.cmp(b.1)));

    let entries: Vec<PoEntry> = keys
        .into_iter()
        .map(|(text, ctxt)| {
            let slot = &catalog[text][ctxt];
            let mut comments = Vec::with_capacity(slot.comments.len() + 1);
            if !slot.src.is_empty() {
                // Провенанс — первым комментарием (рядом с rich_text).
                comments.push(format!("src: {}", slot.src));
            }
            comments.extend(slot.comments.iter().cloned());
            PoEntry {
                msgid: text.to_string(),
                msgctxt: ctxt.to_string(),
                comments,
                ..PoEntry::default()
            }
        })
        .collect();

    render_po(&entries, &pot_header_lines(created))
}

/// Ключи (msgid, msgctxt) существующего POT — для статистики.
pub fn old_keys_from_pot(path: &Path) -> HashSet<(String, String)> {
    let mut keys = HashSet::new();
    let Ok(text) = std::fs::read_to_string(path) else {
        return keys;
    };
    for e in parse_po(&text) {
        if !e.msgid.is_empty() {
            keys.insert((e.msgid, e.msgctxt));
        }
    }
    keys
}

/// Атомарная запись: `.part` → rename (обрыв не обнуляет файл).
pub fn write_atomic(path: &Path, text: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    let part = PathBuf::from(format!("{}.part", path.display()));
    let write = std::fs::write(&part, text).map_err(|e| format!("{}: {e}", part.display()));
    if let Err(err) = write {
        let _ = std::fs::remove_file(&part);
        return Err(err);
    }
    std::fs::rename(&part, path).map_err(|e| {
        let _ = std::fs::remove_file(&part);
        format!("{}: {e}", path.display())
    })
}

#[derive(Debug, Clone)]
pub struct PotgenOptions {
    pub root: PathBuf,
    pub dump_dir: PathBuf,
    pub out_path: Option<PathBuf>,
    pub update: bool,
    /// Фиксированная дата заголовка (тесты/паритет); по умолчанию — сейчас.
    pub created: Option<String>,
}

#[derive(Debug)]
pub struct PotgenResult {
    pub out_path: PathBuf,
    pub entries: usize,
    pub stats: PotStats,
}

impl PotgenOptions {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self {
            root: root.into(),
            dump_dir: PathBuf::new(),
            out_path: None,
            update: false,
            created: None,
        }
    }
}

/// Полный прогон: дамп → инвентарь → каталог → POT.
///
/// Без `out_path` и без `update` пишет в `tmp/potgen/template.pot`;
/// `update: true` — в `po/template.pot`.
pub fn run(options: &PotgenOptions) -> Result<PotgenResult, String> {
    let dump_dir = if options.dump_dir.as_os_str().is_empty() {
        options.root.join("tmp").join("dump")
    } else {
        options.dump_dir.clone()
    };
    let inventory = scan_dump(&dump_dir)?;
    if inventory.items.is_empty() {
        return Err(format!(
            "empty dump: {} — переводимых строк не найдено",
            dump_dir.display()
        ));
    }

    // Ключи берём из репозиторного `po/template.pot` ВСЕГДА, даже если пишем
    // в другой файл: это только статистика new/vanished.
    let old_keys = old_keys_from_pot(&options.root.join("po").join("template.pot"));
    let (catalog, stats) = build_catalog(&inventory.items, &old_keys);
    let entries = catalog_size(&catalog);
    if entries == 0 {
        return Err("empty catalog: нечего записывать (пустой дамп?)".to_string());
    }

    let out_path = options.out_path.clone().unwrap_or_else(|| {
        if options.update {
            options.root.join("po").join("template.pot")
        } else {
            options.root.join("tmp").join("potgen").join("template.pot")
        }
    });
    let created = options
        .created
        .clone()
        .unwrap_or_else(|| format_pot_date(SystemTime::now()));
    write_atomic(&out_path, &render_pot(&catalog, &created))?;

    Ok(PotgenResult {
        out_path,
        entries,
        stats,
    })
}
